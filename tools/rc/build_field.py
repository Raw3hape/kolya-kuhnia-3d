"""Compile the contiguous visible hunting field; no runtime geometry dependency.
uv run --with shapely==2.1.2 python tools/rc/build_field.py [--check]
The morphological close seals survey slivers smaller than 1.2 m; it does not
introduce a radial arena. Real building footprints are subtracted afterwards.
"""
import json,hashlib,sys
from pathlib import Path
from shapely.geometry import Polygon,Point
from shapely.ops import unary_union
ROOT=Path(__file__).resolve().parents[2]
raw=(ROOT/'web/spec/site.json').read_bytes();site=json.loads(raw)
rc=json.loads((ROOT/'web/spec/rc.json').read_bytes())
TOLERANCE=rc['arena']['seamTolerance']
polys=[Polygon(a['poly'])for a in site['areas'] if a['kind']in rc['arena']['kinds']]
merged=unary_union(polys).buffer(TOLERANCE/2,join_style=2).buffer(-TOLERANCE/2,join_style=2)
anchor=Point(rc['arena']['spawn']['center']);components=list(merged.geoms)if merged.geom_type=='MultiPolygon'else[merged]
field=Polygon(min(components,key=lambda p:p.distance(anchor)).exterior)
solids=[Polygon(site['own']['footprint'])]+[Polygon(a['poly'])for a in site.get('neighbours',[])if a.get('poly')]
field=field.difference(unary_union(solids))
components=list(field.geoms)if field.geom_type=='MultiPolygon'else[field]
# Build one playable connected field; unrelated mapped meadows are not islands.
field=min(components,key=lambda p:p.distance(anchor))
def ring(r):return[[round(float(x),5),round(float(z),5)]for x,z in list(r.coords)[:-1]]
data={'version':1,'sourceSiteSha256':hashlib.sha256(raw).hexdigest(),'sourceRecipe':'web/spec/rc.json arena kinds and spawn anchor','generator':'tools/rc/build_field.py','seamTolerance':TOLERANCE,'recipe':{'kinds':rc['arena']['kinds'],'spawnCenter':rc['arena']['spawn']['center'],'seamTolerance':TOLERANCE},'polygons':[{'outer':ring(field.exterior),'holes':[ring(r)for r in field.interiors]}]}
text='// Generated by tools/rc/build_field.py; edit source site/recipe, never vertices.\nexport const PLAYABLE_FIELD=Object.freeze('+json.dumps(data,separators=(',',':'))+');\n'
out=ROOT/'web/js/playable-field.generated.js'
if '--check'in sys.argv:
 if not out.exists()or out.read_text()!=text:raise SystemExit('Playable field is stale: rerun tools/rc/build_field.py')
else:out.write_text(text)
print(json.dumps({'areaSquareMetres':round(field.area,2),'outerVertices':len(data['polygons'][0]['outer']),'obstacleHoles':len(data['polygons'][0]['holes']),'bounds':field.bounds,'check':'--check'in sys.argv}))
